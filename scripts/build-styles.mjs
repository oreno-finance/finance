// app.css is generated, not edited by hand. The bundle lives next to its source
// sheets, so relative url(...) references continue to resolve identically.
export async function buildStyles(root = resolve(fileURLToPath(new URL('..', import.meta.url)))) {
  const css = [];
  for (const filename of sourceSheets) {
    if (!/^[a-z0-9][a-z0-9-]*\.css$/.test(filename) || filename === 'app.css')
      throw new Error(`Unapproved CSS source: ${filename}`);
    const contents = await readFile(resolve(root, 'public/styles', filename), 'utf8');
    if (/^\s*@(?:charset|import)\b/im.test(contents))
      throw new Error(`CSS at-rule requires special bundling: ${filename}`);
    css.push(`/* SOURCE: ${filename} */\n${contents.trimEnd()}\n`);
  }
  const output = '/* GENERATED by scripts/build-styles.mjs. Do not edit. */\n' + css.join('\n');
  await writeFile(resolve(root, 'public/styles/app.css'), output);
  return output;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildStyles();
  console.log(`Finance CSS: ${sourceSheets.length} ordered source files -> public/styles/app.css`);
}
